/**
 * Sample catalog used to seed a development database.
 *
 * Two kinds of titles:
 *  - PLATFORM_ORIGINAL: fictional "CineVault Originals" invented for development. Their
 *    media files are short clips generated locally with ffmpeg (scripts/generate-sample-media.ts),
 *    so the platform owns them outright and they exercise the real download/stream pipeline.
 *  - PUBLIC_DOMAIN: real classic films believed to be in the US public domain. Metadata only —
 *    NO media files are seeded, so they correctly show "Download currently unavailable" until an
 *    administrator uploads an authorized copy. Public-domain status is jurisdiction specific.
 *
 * Ratings are an editorial "CineVault score" for sample purposes, not IMDb data.
 * All poster/backdrop artwork is generated placeholder art (see prisma/art.ts).
 */

